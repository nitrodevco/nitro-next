/**
 * `ButtonPreset.MODE_SCALE` / `MODE_STRETCH` - the `kind` of a `WiredButton`, kept as Flash's
 * ints so that a port can pass the constructor's third argument through.
 */

/** `ButtonPreset.MODE_SCALE` - the button takes the width it is given. */
export const WIRED_BUTTON_SCALE = 0;

/** `ButtonPreset.MODE_STRETCH` - the button is as wide as its caption (a static width). */
export const WIRED_BUTTON_STRETCH = 1;
