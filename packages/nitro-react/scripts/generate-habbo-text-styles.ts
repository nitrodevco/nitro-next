/**
 * Turns the Flash client's own `styles.css` (the `styles_css` binary asset of the SWF) into
 * `nitro-theme/src/font/flash-text/habboTextStyles.ts`: one `FlashTextFormat` override per text style,
 * resolved the way `TextStyleManager` and `TextFieldCache` resolved them - advanced
 * anti-aliasing unless a style says `normal`, and no kerning unless it asks for it.
 *
 *   node scripts/generate-habbo-text-styles.ts <path to styles.css>
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUTPUT = resolve(dirname(fileURLToPath(import.meta.url)), '../../nitro-theme/src/font/flash-text/habboTextStyles.ts');

const source = process.argv[2];

if (!source) throw new Error('usage: node scripts/generate-habbo-text-styles.ts <path to styles.css>');

const css = readFileSync(source, 'utf8');
const entries: string[] = [];

for (const [ , name, body ] of css.matchAll(/([A-Za-z0-9_]+)\s*\{([^}]*)\}/g)) {
    const properties = new Map<string, string>();

    for (const [ , property, value ] of body.matchAll(/([a-z-]+)\s*:\s*([^;]+);/g)) properties.set(property, value.trim());

    const fields: string[] = [
        `fontFamily: '${properties.get('font-family') ?? 'Volter'}'`,
        `fontSize: ${Number(properties.get('font-size') ?? 9)}`,
    ];

    if (properties.get('font-weight') === 'bold') fields.push('bold: true');
    if (properties.get('font-style') === 'italic') fields.push('italic: true');
    if (properties.get('text-decoration') === 'underline') fields.push('underline: true');
    if (properties.has('color')) fields.push(`color: 0x${properties.get('color')!.replace('#', '').toUpperCase()}`);

    fields.push(`antiAliasType: '${properties.get('anti-alias-type') === 'normal' ? 'normal' : 'advanced'}'`);
    fields.push(`kerning: ${properties.get('kerning') === 'true'}`);

    if (properties.has('sharpness')) fields.push(`sharpness: ${Number(properties.get('sharpness'))}`);
    if (properties.has('thickness')) fields.push(`thickness: ${Number(properties.get('thickness'))}`);

    if (properties.has('etching-color')) {
        fields.push(`etchingColor: 0x${properties.get('etching-color')!.replace('#', '').toUpperCase()}`);
        fields.push(`etchingPosition: '${properties.get('etching-position') ?? 'bottom'}'`);
    }

    entries.push(`    ${name}: { ${fields.join(', ')} },`);
}

const output = `/**
 * The Flash client's text styles, one \`FlashTextFormat\` override each - what a window layout's
 * \`text_style\` names. Generated by \`scripts/generate-habbo-text-styles.ts\` from the client's own
 * \`styles.css\`; regenerate rather than edit.
 */
import { FlashTextFormat } from './flashTextFormat';

export const HABBO_TEXT_STYLES = {
${entries.join('\n')}
} as const satisfies Record<string, Partial<FlashTextFormat>>;

export type HabboTextStyleName = keyof typeof HABBO_TEXT_STYLES;
`;

writeFileSync(OUTPUT, output);
console.log(`${entries.length} styles -> ${OUTPUT}`);
