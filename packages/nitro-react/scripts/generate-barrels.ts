/**
 * Rewrites every barrel (`index.ts`) under the generated roots from what is actually on disk:
 * each directory's barrel re-exports its own modules and the barrels of its subdirectories. A
 * module added without touching a barrel is therefore one run of this away from being importable,
 * rather than a missing line nobody notices until something fails to resolve.
 *
 * The roots are `src/context/<feature>` (one barrel tree per feature - there is deliberately no
 * barrel for `src/context` itself: import a feature, `#base/context/room`, not the whole of the
 * client state), and `src/hooks`, `src/handlers`, `src/commands`, `src/components`, `src/utils`,
 * `src/chat`, `src/wired` (the wired element models), `src/sound` (the sound manager) and
 * `src/snowwar` (the SnowWar game's simulation and arena view), each one tree behind its `#base/*`
 * alias. `src/theme` and `src/views` keep their own barrels: the theme's is curated, and views are
 * imported by path.
 *
 * Usage: `yarn generate-barrels` (add `--check` to fail instead of writing, for CI).
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const SRC_ROOT = join(import.meta.dirname, '..', 'src');
const MODULE_PATTERN = /\.tsx?$/;
/**
 * Left out of every barrel, besides the barrels themselves, tests, declarations and `*.check.ts`
 * type assertions only `tsc` reads (`clientModuleSdk.check.ts`): the wired
 * element registry and its six registration files. They are the one place under `src/wired` that
 * imports views, and the views (through the wired kit) import `#base/wired` back - a barrel that
 * reached them would be evaluated half-way round that cycle. Import them by path:
 * `#base/wired/WiredElementRegistry`.
 */
const EXCLUDED = /(^index\.ts$)|(\.test\.tsx?$)|(\.d\.ts$)|(\.check\.ts$)|(^WiredElementRegistry\.ts$)|(^(trigger|action|condition|addon|selector|variable)Elements\.ts$)/;
const HEADER = '// Generated by scripts/generate-barrels.ts - run it instead of editing by hand.\n';

/** Directories that get one barrel tree each. */
const TREE_ROOTS = [ 'hooks', 'handlers', 'commands', 'components', 'utils', 'chat', 'wired', 'sound', 'snowwar' ];
/** A directory whose children each get their own barrel tree. */
const FEATURE_ROOT = 'context';

const check = process.argv.includes('--check');
const stale: string[] = [];

const hasModules = (dir: string): boolean => readdirSync(dir).some((entry) => {
    const path = join(dir, entry);

    if (statSync(path).isDirectory()) return hasModules(path);

    return MODULE_PATTERN.test(entry) && !EXCLUDED.test(entry);
});

const writeBarrel = (dir: string) => {
    const lines: string[] = [];

    for (const entry of readdirSync(dir).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))) {
        const path = join(dir, entry);

        if (statSync(path).isDirectory()) {
            if (!hasModules(path)) continue;

            writeBarrel(path);
            lines.push(`export * from './${entry}';`);

            continue;
        }

        if (!MODULE_PATTERN.test(entry) || EXCLUDED.test(entry)) continue;

        lines.push(`export * from './${entry.replace(MODULE_PATTERN, '')}';`);
    }

    const barrel = join(dir, 'index.ts');
    const contents = `${HEADER}${lines.join('\n')}\n`;
    const current = existsSync(barrel) ? readFileSync(barrel, 'utf8') : '';

    if (current === contents) return;

    if (check) stale.push(relative(process.cwd(), barrel));
    else writeFileSync(barrel, contents);
};

for (const root of TREE_ROOTS) {
    const path = join(SRC_ROOT, root);

    if (existsSync(path) && hasModules(path)) writeBarrel(path);
}

for (const feature of readdirSync(join(SRC_ROOT, FEATURE_ROOT))) {
    const path = join(SRC_ROOT, FEATURE_ROOT, feature);

    if (statSync(path).isDirectory() && hasModules(path)) writeBarrel(path);
}

if (stale.length) {
    console.error(`Stale barrels:\n${stale.map(x => `  ${x}`).join('\n')}\nRun: yarn generate-barrels`);
    process.exit(1);
}
